/* The four-stage 4-pixel EGC glyph-overlay coverage sequence of TH04/TH05. */
#ifndef TH05_SHARED_GLYPH_COVERAGE_H
#define TH05_SHARED_GLYPH_COVERAGE_H

/* The masks are 16-pixel rows, made from one repeated four-bit pixel tile. */
#define GLYPH_REPEAT_NIBBLE(pattern) ((unsigned int)((pattern) * 0x1111U))

enum GlyphOverlayNibble {
    GLYPH_OVERLAY_NONE = 0,
    GLYPH_OVERLAY_FIRST = 0x8,
    GLYPH_OVERLAY_SECOND = 0x4,
    GLYPH_OVERLAY_THIRD = 0x2,
    GLYPH_OVERLAY_FOURTH = 0x1,
    GLYPH_OVERLAY_ALTERNATE = 0xA,
    GLYPH_OVERLAY_ALTERNATE_COMPLEMENT = 0x5
};

#define GLYPH_COVERAGE_ROWS { \
    { GLYPH_REPEAT_NIBBLE(GLYPH_OVERLAY_FIRST), GLYPH_REPEAT_NIBBLE(GLYPH_OVERLAY_NONE), \
      GLYPH_REPEAT_NIBBLE(GLYPH_OVERLAY_THIRD), GLYPH_REPEAT_NIBBLE(GLYPH_OVERLAY_NONE) }, \
    { GLYPH_REPEAT_NIBBLE(GLYPH_OVERLAY_FIRST), GLYPH_REPEAT_NIBBLE(GLYPH_OVERLAY_SECOND), \
      GLYPH_REPEAT_NIBBLE(GLYPH_OVERLAY_THIRD), GLYPH_REPEAT_NIBBLE(GLYPH_OVERLAY_FOURTH) }, \
    { GLYPH_REPEAT_NIBBLE(GLYPH_OVERLAY_ALTERNATE), GLYPH_REPEAT_NIBBLE(GLYPH_OVERLAY_SECOND), \
      GLYPH_REPEAT_NIBBLE(GLYPH_OVERLAY_ALTERNATE), GLYPH_REPEAT_NIBBLE(GLYPH_OVERLAY_FOURTH) }, \
    { GLYPH_REPEAT_NIBBLE(GLYPH_OVERLAY_ALTERNATE), GLYPH_REPEAT_NIBBLE(GLYPH_OVERLAY_ALTERNATE_COMPLEMENT), \
      GLYPH_REPEAT_NIBBLE(GLYPH_OVERLAY_ALTERNATE), GLYPH_REPEAT_NIBBLE(GLYPH_OVERLAY_ALTERNATE_COMPLEMENT) } \
}

#endif
